def _divergence(stem: str, expected: bytes, actual: bytes) -> str:
    """첫 다른 바이트의 위치와 그 앞뒤를 보여준다. 실패 원인은 여기서 바로 읽는다."""
    limit = min(len(expected), len(actual))
    offset = next((i for i in range(limit) if expected[i] != actual[i]), limit)
    context = slice(max(0, offset - 12), offset + 12)
    line = expected[:offset].count(b"\n") + 1
    return (
        f"{stem}: SRT {line}번째 줄, 바이트 offset {offset}부터 다르다 "
        f"(기대 {len(expected)}바이트 / 실제 {len(actual)}바이트)\n"
        f"  expected: {expected[context]!r}\n"
        f"    actual: {actual[context]!r}"
    )


@pytest.mark.parametrize("stem", ["demo", "loopy", "loopyletter", "loopylong"])
def test_source_srt_bytes_are_locked(stem: str, tmp_path: Path) -> None:
    """네 도형 모두 기대 바이트와 한 바이트도 다르지 않다."""
    assert env.find_env_file() is None
    assert not env.has_api_key()

    result = pipeline.run(Path(f"golden/{stem}.mp4"), Config(), tmp_path, force_offline=True)
    assert result.verification is not None, "검증도 보통대로 켠 채로 잠근다(규칙 5)"

    actual = result.outputs["srt"].read_bytes()
    expected = EXPECTED[stem].encode("utf-8")
    assert actual == expected, _divergence(stem, expected, actual)
    # output.srt 별칭도 같은 큐에서 나오므로 같은 바이트여야 한다.
    assert result.outputs["srt_alias"].read_bytes() == actual
